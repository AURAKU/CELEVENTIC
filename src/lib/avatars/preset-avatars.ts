export function isPresetAvatarUrl(url: string | null | undefined): boolean {
  if (!url) return false;
  return PRESET_AVATARS.some((a) => a.url === url);
}

export function findPresetAvatar(url: string | null | undefined): PresetAvatar | undefined {
  if (!url) return undefined;
  return PRESET_AVATARS.find((a) => a.url === url);
}
